const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ timezoneId: 'America/Fortaleza', viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'pt-BR' });
  await ctx.clock.install({ time: new Date('2026-11-25T21:14:00-03:00') });
  await ctx.addInitScript(() => { localStorage.setItem('tipe:cliente:mare-alta:m12', 'Lucas Andrade'); });
  const p = await ctx.newPage();
  p.on('console', m => { if (m.type()==='error') console.log('ERR', m.text().slice(0,200)); });
  const shot = async (n) => { await p.waitForTimeout(900); await p.screenshot({ path: `${process.env.SAIDA || '/tmp/telas'}/${n}.png` }); console.log('shot', n); };
  const top = () => p.evaluate(() => window.scrollTo(0, 0));
  await p.goto('http://127.0.0.1:5179/mare-alta/m12?t=reset', { waitUntil: 'networkidle', timeout: 120000 });
  await p.goto('http://127.0.0.1:5179/mare-alta/m12?t=x', { waitUntil: 'networkidle', timeout: 120000 });
  await p.waitForTimeout(1500);
  await shot('conta');
  const cards = p.locator('#itens-da-conta + ul > li');
  await cards.nth(2).getByRole('button', { name: 'Dividir este item' }).click();
  await cards.nth(2).getByRole('button', { name: /Por dois/ }).click();
  await p.getByLabel('Quantidade de Caipirinha de limão').selectOption('1');
  await p.getByLabel('Quantidade de Pudim de leite').selectOption('1');
  await cards.nth(0).getByRole('button', { name: 'Dividir este item' }).click();
  await p.evaluate(() => { const h = document.getElementById('itens-da-conta'); window.scrollTo(0, h.getBoundingClientRect().top + scrollY - 24); });
  await shot('dividir');
  // fecha o seletor aberto do baião sem escolher
  await p.getByRole('button', { name: /Continuar para pagamento/ }).click();
  await p.getByRole('checkbox').first().check().catch(async()=>{ await p.getByRole('checkbox').first().click(); });
  await top(); await shot('metodos');
  await p.getByRole('button', { name: /^Pagar/ }).last().click();
  await p.waitForTimeout(600); await top(); await shot('pix');
  await p.waitForTimeout(4500); await top(); await shot('pago');
  const dump = async () => console.log((await p.innerText('body')).replace(/\n+/g,' | ').slice(0,700));
  await dump();
  await p.getByRole('button', { name: /gorjeta/i }).first().click();
  await p.getByText('5%', { exact: true }).first().click();
  await top(); await shot('gorjeta'); await dump();
  await p.getByRole('button', { name: /Continuar/ }).first().click();
  await p.waitForTimeout(500); await top(); await shot('gorjeta-metodo'); await dump();
  await p.getByRole('button', { name: /^Pagar|Enviar|Confirmar/ }).last().click();
  await p.waitForTimeout(600); await top(); await shot('gorjeta-pix'); await dump();
  await p.waitForTimeout(4500); await top(); await shot('gorjeta-ok'); await dump();
  await p.getByRole('button', { name: /Avaliar/ }).first().click();
  await p.waitForTimeout(500);
  await p.getByRole('radio', { name: '5 estrelas' }).click();
  await top(); await shot('avaliacao'); await dump();
  await b.close();
})();
